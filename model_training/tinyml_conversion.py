"""tinyml_conversion.py - Keras -> int8 TFLite -> C headers + firmware/model_config.h"""
import json

import numpy as np
import tensorflow as tf

from common import (FIRMWARE, METADATA, RESULTS, TFLITE, TRAINED,
                    feature_arrays, load_scaler, load_split)

REP_SAMPLES = 300


def convert(keras_path, X_rep):
    model = tf.keras.models.load_model(keras_path)
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]

    def rep_data():
        for i in range(len(X_rep)):
            yield [X_rep[i:i + 1].astype(np.float32)]

    conv.representative_dataset = rep_data
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    tflite_bytes = conv.convert()

    interp = tf.lite.Interpreter(model_content=tflite_bytes)
    in_scale, in_zp = interp.get_input_details()[0]["quantization"]
    out_scale, out_zp = interp.get_output_details()[0]["quantization"]
    quant = {"in_scale": float(in_scale), "in_zp": int(in_zp),
             "out_scale": float(out_scale), "out_zp": int(out_zp)}
    return tflite_bytes, quant


def write_c_header(path, var_name, data: bytes):
    hexes = [f"0x{b:02x}" for b in data]
    lines = [", ".join(hexes[i:i + 12]) for i in range(0, len(hexes), 12)]
    body = ",\n  ".join(lines)
    path.write_text(
        "#pragma once\n\n"
        f"alignas(8) const unsigned char {var_name}[] = {{\n  {body}\n}};\n"
        f"const unsigned int {var_name}_len = {len(data)};\n")


def update_metadata(name, quant, size_bytes):
    path = METADATA / name
    meta = json.loads(path.read_text())
    meta["quantization"] = quant
    meta["tflite_size_bytes"] = size_bytes
    path.write_text(json.dumps(meta, indent=2))


def write_model_config(scaler, tq, cq):
    mean, std = feature_arrays(scaler)
    f = lambda v: f"{float(v):.8f}f"
    arr = lambda vals: ", ".join(f(v) for v in vals)
    text = f"""#pragma once
// AUTO-GENERATED by model_training/tinyml_conversion.py - do not edit by hand.

constexpr int WINDOW_SIZE = {scaler['window']};
constexpr int FEATURE_COUNT = {len(scaler['features'])};
constexpr int INPUT_LEN = WINDOW_SIZE * FEATURE_COUNT;
constexpr int STEP_MINUTES = {scaler['step_minutes']};
constexpr int HORIZON_STEPS = {scaler['horizon_steps']};
constexpr int NUM_RISK_CLASSES = 3;

// Feature order: {', '.join(scaler['features'])}
const float FEAT_MEAN[FEATURE_COUNT] = {{{arr(mean)}}};
const float FEAT_STD[FEATURE_COUNT]  = {{{arr(std)}}};

const float TARGET_MEAN = {f(scaler['target_temp_c']['mean'])};
const float TARGET_STD  = {f(scaler['target_temp_c']['std'])};

const float TEMP_IN_SCALE = {f(tq['in_scale'])};
const int   TEMP_IN_ZP    = {tq['in_zp']};
const float TEMP_OUT_SCALE = {f(tq['out_scale'])};
const int   TEMP_OUT_ZP    = {tq['out_zp']};

const float RISK_IN_SCALE = {f(cq['in_scale'])};
const int   RISK_IN_ZP    = {cq['in_zp']};
const float RISK_OUT_SCALE = {f(cq['out_scale'])};
const int   RISK_OUT_ZP    = {cq['out_zp']};
"""
    (FIRMWARE / "model_config.h").write_text(text)


def main():
    scaler = load_scaler()
    X_train, _, _ = load_split("training", scaler)
    idx = np.linspace(0, len(X_train) - 1, min(REP_SAMPLES, len(X_train))).astype(int)
    X_rep = X_train[idx]

    jobs = [("temperature_model", "temperature_metadata.json"),
            ("risk_classifier", "classifier_metadata.json")]
    quants, sizes = {}, {}
    for name, meta_file in jobs:
        tfl, quant = convert(TRAINED / f"{name}.keras", X_rep)
        (TFLITE / f"{name}_int8.tflite").write_bytes(tfl)
        write_c_header(FIRMWARE / "model_headers" / f"{name}.h", name, tfl)
        update_metadata(meta_file, quant, len(tfl))
        quants[name], sizes[name] = quant, len(tfl)

    write_model_config(scaler, quants["temperature_model"], quants["risk_classifier"])
    (RESULTS / "model_size.txt").write_text(
        "\n".join(f"{n}_int8.tflite: {s} bytes ({s / 1024:.2f} KB)" for n, s in sizes.items()) + "\n")
    print("Done: tflite files, firmware/model_headers/*.h, firmware/model_config.h, results/model_size.txt")


if __name__ == "__main__":
    main()
